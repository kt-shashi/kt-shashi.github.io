import fs from 'node:fs';
import { geoMercator, geoPath } from 'd3-geo';
const india = JSON.parse(fs.readFileSync('tools/india.geojson', 'utf8'));
if (!india) throw Error('India geometry missing');
// The journey viewport covers northern and central India.
const projection = geoMercator().center([82, 27]).scale(1850).translate([600, 280]).precision(0.2);
const path = geoPath(projection)(india);
const [[west], [east]] = geoPath(projection).bounds(india);
const boundaries = JSON.parse(fs.readFileSync('tools/india-admin1-lines.geojson', 'utf8'));
const boundaryPath = geoPath(projection).digits(1)(boundaries);
const transitionStates = JSON.parse(fs.readFileSync('tools/transition-states.geojson', 'utf8'));
const statePaths = Object.fromEntries(
  transitionStates.features.map((state) => [
    state.properties.name,
    geoPath(projection).digits(1)(state),
  ]),
);
fs.writeFileSync(
  'src/app/data/map.generated.ts',
  `// Generated by tools/generate-map.mjs. Do not edit.\nexport const indiaPath = ${JSON.stringify(path)};\nexport const boundaryPath = ${JSON.stringify(boundaryPath)};\nexport const statePaths = ${JSON.stringify(statePaths)} as const;\nexport const indiaHorizontalBounds = [${west}, ${east}] as const;\nexport const projection = {center:[82,27],scale:1850,translate:[600,280]} as const;\n`,
);
